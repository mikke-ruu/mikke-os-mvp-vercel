import assert from 'node:assert/strict';
import {receiptV2} from './receipt-v2.mjs';
const p={name:'確認者<script>',title:'確認講座',price:5500,method:'bank',bank_note:'確認銀行 確認支店\n普通 1234567',headquartersName:'確認本部',contactEmail:'help@example.invalid',homePath:'/academy/site/test-school',planPath:'/academy/page/test-plan',event:{startsAt:'2027-02-20T01:00:00Z'}};
const bank=receiptV2(p,'http://127.0.0.1:57870');
assert(bank.text.includes('お申し込みいただき、ありがとうございます'));
assert(bank.text.includes('確認銀行 確認支店'));
assert(bank.text.includes('お問い合わせ：help@example.invalid'));
assert(bank.html.includes('&lt;script&gt;'));
assert(!bank.html.includes('<script>'));
assert(bank.html.includes('href="http://127.0.0.1:57870/academy/page/test-plan"'));
const external=receiptV2({...p,method:'external',external_payment_url:'https://example.invalid/pay'},'http://127.0.0.1:57870');
assert(external.text.includes('https://example.invalid/pay'));
assert(!external.text.includes('確認銀行'));
assert(!external.text.includes('普通 1234567'));
assert.throws(()=>receiptV2({...p,method:'external',external_payment_url:'javascript:alert(1)'},'http://127.0.0.1:57870'));
assert.throws(()=>receiptV2(p,'https://attacker.invalid'));
console.log('PASS receipt v2 bank/external, signature, links and escaping');
