const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const assert = require('node:assert/strict');
const React = require('react');
const {renderToStaticMarkup} = require('react-dom/server');
const source = fs.readFileSync('components/academy/AcademyRolePreview.tsx','utf8');
const compiled = ts.transpileModule(source,{reportDiagnostics:true,compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX}});
assert.equal(compiled.diagnostics.length,0);
const moduleRef = {exports:{}};
vm.runInNewContext(compiled.outputText,{module:moduleRef,exports:moduleRef.exports,require:name=>{
  assert(['react','react/jsx-runtime'].includes(name),`Unexpected dependency ${name}`);
  return require(name);
}});
const Preview = moduleRef.exports.AcademyRolePreview;
const learner = renderToStaticMarkup(React.createElement(Preview,{role:'learner',title:'入力中の募集',courseNames:['講座A','<img src=x onerror=alert(1)>'],price:4500,secret:'PRIVATE_RECORD'}));
for(const text of ['受講者マイページの見本','入力中の募集','講座A','4,500','申込直後','利用開始後','修了後','教材・復習','申し込んだ募集']) assert(learner.includes(text),text);
assert(learner.includes('&lt;img'));
assert(!learner.includes('<img'));
assert(!learner.includes('PRIVATE_RECORD'));
assert(!/<a\b|href=/.test(learner));
assert(!learner.includes('type="submit"'));
const teacher = renderToStaticMarkup(React.createElement(Preview,{role:'instructor',title:'認定講座',courseNames:['認定講座']}));
for(const text of ['認定後の講師マイページ','講師マニュアル','自分の募集ページ','募集ページからの申込','プロフィール・紹介URL・QR','Community','個人情報は未使用']) assert(teacher.includes(text),text);
assert(!/supabase|useAuth|fetch\(|localStorage|sessionStorage|useRouter|onSave|onSubmit/.test(source));
assert(source.includes('dialog.current?.showModal()'));
assert(source.includes('onClose={() => trigger.current?.focus()}'));
assert(fs.readFileSync('components/academy/OfferingEditor.tsx','utf8').includes('<AcademyRolePreview role="learner" title={form.title}'));
assert(fs.readFileSync('app/academy/courses/CourseForm.tsx','utf8').includes('<AcademyRolePreview role="instructor" title={form.name}'));
console.log('PASS: role previews render current input, escape text, exclude private records, have no data/navigation/write dependencies, and are linked from editors');
