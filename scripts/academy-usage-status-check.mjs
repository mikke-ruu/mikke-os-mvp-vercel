import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import ts from 'typescript';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
const require = createRequire(import.meta.url);
const source = readFileSync(new URL('../components/academy/AcademyUsageStatus.tsx', import.meta.url),'utf8');
const compiled = ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2022}}).outputText;
const module = {exports:{}};
new Function('module','exports','require',compiled)(module,module.exports,name=>name==='next/link'?{default:({children,...props})=>React.createElement('a',props,children)}:require(name));
const render = (access,sample=false)=>renderToStaticMarkup(React.createElement(module.exports.AcademyUsageStatus,{access,sample,href:'/academy/settings'}));
const access={access_kind:'trial',status:'trialing',ends_at:'2026-09-14T01:00:00Z',days_remaining:7,can_manage_drafts:true};
const trial=render(access);
assert.ok(trial.includes('7日間無料体験中'));
assert.ok(trial.includes('2026年9月14日 10:00'));
assert.ok(trial.includes('自動課金されません'));
assert.ok(render({...access,can_manage_drafts:false}).includes('無料体験は終了'));
assert.ok(render({...access,access_kind:'paid',status:'active'}).includes('有料利用中'));
assert.ok(render({...access,access_kind:'paid',status:'internal_grant',ends_at:null}).includes('付与された利用権'));
assert.ok(render(null,true).includes('実際の契約状態ではありません'));
assert.ok(render(null).includes('利用状態を確認'));
assert.ok(!render(null).includes('有料利用中'));
console.log('academy_usage_status_ok: JST deadline, trial/expired/paid/grant/unknown/sample');
