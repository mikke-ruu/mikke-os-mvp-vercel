const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const assert = require('node:assert/strict');
const read = path => fs.readFileSync(path, 'utf8');
const source = read('components/academy/AcademyShell.tsx') + '\nexport { canShowPersonalHref, canShowManageHref, honbuNav, koushiNav, koushiBottomNav, honbuBottomNav };';
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX } }).outputText;
const moduleRef = { exports: {} };
vm.runInNewContext(compiled, { module: moduleRef, exports: moduleRef.exports, require: () => ({}) });
const {canShowPersonalHref: visible, koushiBottomNav, koushiNav, honbuBottomNav} = moduleRef.exports;
const {canShowManageHref: manageVisible, honbuNav} = moduleRef.exports;
assert.equal(honbuNav.map(item => item.label).join('|'), 'ダッシュボード|講座|募集|開催日時|申込|マイページ|ホームページ編集|講師管理|本部設定');
assert.equal(honbuBottomNav.map(item => item.label).join('|'), '講座|募集|開催日時|申込');
assert(!manageVisible({capabilities:['academy:headquarters:manage']}, '/academy/portal'));
assert(manageVisible({capabilities:['academy:learner_portal:view']}, '/academy/portal'));
assert(source.includes('simpleMenu={variant === "honbu"}'), 'Keep the personal portal share and QR utilities');
const learner = { capabilities: ['academy:learner_portal:view'] };
const teacher = { capabilities: ['academy:instructor_portal:view', 'academy:instructor:operate'] };
assert(visible(learner, '/academy/offering-applications/mine', 'learner'));
assert(!visible(learner, '/academy/portal/offering-applications', 'learner'));
assert(!visible(learner, '/academy/portal/offerings', 'learner'));
assert(visible(teacher, '/academy/portal/offering-applications', 'instructor'));
assert(visible(teacher, '/academy/portal/offerings', 'instructor'));
assert(!visible({capabilities: []}, '/academy/offering-applications/mine', 'learner'));
assert(koushiBottomNav.some(item => item.href === '/academy/offering-applications/mine'));
assert(koushiNav.some(item => item.href === '/academy/portal/applications'));
assert(honbuBottomNav.some(item => item.href === '/academy/offering-applications'));
const summary = read('components/academy/AcademyOfferingSummary.tsx');
for (const expected of ['getOwnedHeadquarters(userId, academyId)', 'context.academy_id === hq.id', 'context.capabilities.includes("academy:headquarters:manage")', '.eq("headquarters_id", hq.id)', '.range(offset, offset + 499)', 'if (readError) throw readError', 'setSummary(null)', '件数・金額は未確認', '従来の申込・教材注文とは別集計']) assert(summary.includes(expected), expected);
assert(!summary.includes('academy_applications"'));
assert(!summary.includes('localStorage'));
for (const file of ['AcademyOperationsDashboard', 'AcademyStudioHome']) assert(read(`components/academy/${file}.tsx`).includes('<AcademyOfferingSummary />'));
const ui = read('components/academy/OfferingApplications.tsx');
assert(ui.includes('course.learner_access_mode === "days_after_completion"'));
assert(ui.includes('(row.purchase_snapshot?.completion_mode ?? "hq")'));
assert(!ui.includes('(row.purchase_snapshot?.completion_mode ?? "learner")'), 'Unknown legacy completion authority must not enable learner completion');
assert(ui.includes('audience === "learner" && row.stage_index > 0 && row.completed_at'));
console.log('PASS: learner/instructor nav gates, new intake primary links, separate HQ summary/error/pagination, completion access mode');
