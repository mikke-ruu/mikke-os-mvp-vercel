import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const module={exports:{}};
new Function('module','exports',ts.transpileModule(readFileSync('app/academy/flow-review/model.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText)(module,module.exports);
const {initial,reduce:r,WEEK}=module.exports;
assert.equal(r(initial,{type:'publish'}).first,null);
assert.equal(r({...initial,agreed:true,owner:false},{type:'publish'}).first,null);
assert.equal(r(initial,{type:'fail'}).first,null);
const first=r({...initial,agreed:true},{type:'publish'});
assert.equal(r(r(first,{type:'draft'}),{type:'publish'}).first,first.first);
const end=r(first,{type:'deadline'});
assert.equal(end.now,first.first+WEEK);
assert.equal(r(r(end,{type:'cancel'}),{type:'pay'}).paid,false);
assert.equal(r(end,{type:'pay'}).paid,true);
assert.equal(r({...initial,owner:false},{type:'invite'}).invitation,'none');
const invite=r(initial,{type:'invite'});
assert.equal(invite.invitation,'pending');
assert.equal(r({...invite,owner:false},{type:'revoke'}).invitation,'pending');
assert.deepEqual(r(invite,{type:'accept'}).rooms,invite.rooms);
assert.equal(r(r(invite,{type:'revoke'}),{type:'accept'}).invitation,'cancelled');
assert.ok(readFileSync('app/academy/flow-review/page.tsx','utf8').includes('process.env.NODE_ENV!=="development"'));
console.log('academy_flow_review_ok');
