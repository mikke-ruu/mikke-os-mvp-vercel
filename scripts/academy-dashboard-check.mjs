import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const source = readFileSync(new URL('../lib/academy/dashboard-summary.ts',import.meta.url),'utf8');
const module = {exports:{}};
new Function('module','exports',ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText)(module,module.exports);
const {academyMonth,matchesApplication:app,matchesOrder:order} = module.exports;
assert.equal(academyMonth('2026-08-31T15:00:00Z'),'2026-09');
assert.equal(academyMonth('2026-08-31T14:59:59Z'),'2026-08');
assert.equal(academyMonth('bad'),'');
assert.equal(app({created_at:'2026-08-31T15:00:00Z'},'month','2026-09'),true);
assert.equal(app({status:'received'},'new'),true);
assert.equal(app({status:'closed',payment_status:'unpaid'},'unpaid'),false);
assert.equal(app({status:'cancelled',payment_status:'unpaid'},'unpaid'),false);
assert.equal(order({status:'shipped'},'active'),false);
assert.equal(order({status:'preparing'},'shipping'),true);
assert.equal(order({status:'received'},'shipping'),false);
assert.equal(order({status:'cancelled',payment_status:'unpaid'},'unpaid'),false);
const component = readFileSync(new URL('../components/academy/AcademyOperationsDashboard.tsx',import.meta.url),'utf8');
for (const title of ['登録講座','今月の受講申込','対応中の教材注文','講師登録','対応が必要なこと','今日・次の開催','最近の受講申込']) assert.ok(component.includes(title));
assert.ok(!component.includes('<details'));
const list = readFileSync(new URL('../app/academy/applications/page.tsx',import.meta.url),'utf8');
assert.ok(list.includes('matchesApplication(a, filter, month)'));
assert.ok(list.includes('matchesOrder(k, filter)'));
console.log('academy_dashboard_ok: JST month boundary, cancellation exclusion, shared count/filter predicates, always-visible sections');
